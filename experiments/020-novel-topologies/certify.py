"""Certify the frozen candidate cells: scorecard + bias sheet + THD + figures.

Deterministic and re-runnable: everything a scorecard claims is regenerated
here from `frozen/*.json`, so a number in a report can always be traced to a
deck hash in the ledger.

    python experiments/020-novel-topologies/certify.py            # all cells
    python experiments/020-novel-topologies/certify.py 020B       # one cell
    python experiments/020-novel-topologies/certify.py --no-thd   # cheap only
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from lab import metrics as M            # noqa: E402
from lab import plot as P               # noqa: E402
from lab import thd as T                # noqa: E402
from lab.dut import Design, Dev, device_table   # noqa: E402
from lab.deck import ac_noise           # noqa: E402
from lab.oppoint import probe, table as op_table, problems  # noqa: E402

HERE = Path(__file__).parent
FROZEN = HERE / "frozen"
REF = ROOT / "decks" / "reference" / "design.json"


def load(path: Path) -> Design:
    d = json.loads(Path(path).read_text())
    devs = {k: Dev(v["w"], v["l"], v["ng"], v["m"]) for k, v in d["devs"].items()}
    c = d["caps_pf"]
    return Design(topology=d["topology"], devs=devs, iref=d["iref"],
                  c1_a=c["c1_a"] * 1e-12, c2_a=c["c2_a"] * 1e-12,
                  c1_b=c["c1_b"] * 1e-12, c2_b=c["c2_b"] * 1e-12,
                  vicm=d.get("vicm", 0.25), vocm=d.get("vocm", 1.25),
                  note=d.get("note", ""))


def certify(name: str, d: Design, *, run_thd: bool = True,
            freeze: bool = True) -> dict:
    out: dict = {"name": name}
    s = M.evaluate(d, f"cert_{name}")
    out["score"] = s
    ops, volts = probe(d, f"cert_{name}_op")
    out["ops"], out["volts"] = ops, volts
    out["problems"] = problems(ops)
    if run_thd:
        try:
            out["thd"] = T.measure(d, tag=f"cert_{name}_thd50")
        except Exception as exc:                      # noqa: BLE001
            out["thd_error"] = str(exc)[:300]
    if not freeze:
        # decks/reference/ is a read-only certified artefact (lint-enforced):
        # the reference is MEASURED here, never re-written here.
        return out
    # freeze the exact testbench that produced these numbers
    deck_dir = ROOT / "decks" / name.lower()
    deck_dir.mkdir(parents=True, exist_ok=True)
    (deck_dir / "lpf_tb.sp").write_text(ac_noise(d))
    (deck_dir / "build-sheet.md").write_text(
        f"# {name} — build sheet\n\n{device_table(d)}\n\n"
        f"{op_table(ops, volts, d)}\n")
    return out


def scorecard(name: str, d: Design, r: dict, ref: dict | None) -> str:
    s: M.Score = r["score"]
    v = s.values
    rows = [f"# {name} — sign-off scorecard", "",
            f"**KIND: REVIEW.** Regenerated by `certify.py`; every number below "
            f"comes from a ledger row tagged `cert_{name}*`.", "",
            "## 1. Spec verdict", "",
            "| # | spec | target | measured | verdict |",
            "|---|---|---|---|---|"]
    lines = [
        ("S1", "max unwrapped phase lag", "≥ 330°", f"{v['ph_max_deg']:.2f}°",
         v["ph_max_deg"] >= 330),
        ("S1c", "\\|H\\| at 1 kHz", "≤ −48 dB", f"{v['a1000_db']:.2f} dB",
         v["a1000_db"] <= -48),
        ("S2", "cutoff", "250 Hz ± 2 %", f"{v['fc_hz']:.2f} Hz",
         245 <= v["fc_hz"] <= 255),
        ("S3", "passband gain", "\\|dc\\| ≤ 0.2 dB", f"{v['dc_db']:+.4f} dB",
         abs(v["dc_db"]) <= 0.2),
        ("S4", "peaking", "≤ 0.2 dB", f"{v['peak_db']:.3f} dB",
         v["peak_db"] <= 0.2),
        ("S5", "IRN 0.5–200 Hz", "< 40 µVrms", f"**{v['irn_uv']:.2f} µVrms**",
         v["irn_uv"] < 40),
        ("S6", "filter-core power", "< 50 nW",
         f"{v['p_core_nw']:.2f} nW ({v['i_core_na']:.2f} nA)",
         v["p_core_nw"] < 50),
    ]
    if "thd" in r:
        t = r["thd"]
        lines.append(("S7", "THD @ 175 mVpp, fin = 50 Hz", "≤ −40 dB",
                      f"{t.thd_db:.2f} dB", t.thd_db <= -40))
    for num, spec, target, meas, ok in lines:
        rows.append(f"| {num} | {spec} | {target} | {meas} | "
                    f"{'**PASS**' if ok else '**FAIL**'} |")
    npass = sum(1 for *_, ok in lines if ok)
    rows.append(f"\n**{npass} of {len(lines)} spec lines PASS.**")
    rows.append(f"\nReport-only: total drawn capacitance **{v['c_total_pf']:.2f} pF**; "
                f"output noise 0.1 Hz–1 kHz {v.get('onoise_uv', float('nan')):.2f} µV; "
                f"worst in-band phase step {v.get('ph_step_deg', float('nan')):.1f}° "
                f"(resolvability guard {M.PH_STEP_GUARD_DEG:g}°).")
    if ref:
        rv = ref["score"].values
        rows += ["", "## 2. Against the reference baseline", "",
                 "| quantity | reference | " + name + " | delta |",
                 "|---|---|---|---|"]
        for key, lab, fmt in (("irn_uv", "IRN 0.5–200 Hz (µVrms)", "{:.2f}"),
                              ("p_core_nw", "filter-core power (nW)", "{:.2f}"),
                              ("c_total_pf", "total drawn C (pF)", "{:.1f}"),
                              ("fc_hz", "cutoff (Hz)", "{:.2f}"),
                              ("ph_max_deg", "phase certificate (°)", "{:.2f}")):
            a, b = rv.get(key), v.get(key)
            if a is None or b is None:
                continue
            rows.append(f"| {lab} | {fmt.format(a)} | {fmt.format(b)} | "
                        f"{(b - a) / a * 100:+.1f} % |")
    rows += ["", "## 3. Bias sheet (every device, nominal corner)", "",
             op_table(r["ops"], r["volts"], d)]
    if r["problems"]:
        rows += ["", "**Operating-point problems:**"] + \
                [f"- {p}" for p in r["problems"]]
    else:
        rows += ["", "Every device is saturated and in weak inversion "
                 "(gm/ID ≥ 18) — no operating-point exceptions."]
    rows += ["", "## 4. Geometry", "", device_table(d)]
    if "thd" in r:
        t = r["thd"]
        rows += ["", "## 5. Distortion", "", T.table([t]), "",
                 "Per-harmonic (dB rel. fundamental): " +
                 ", ".join(f"h{k} {x:.1f}" for k, x in sorted(t.per_harmonic.items()))]
    elif "thd_error" in r:
        rows += ["", "## 5. Distortion", "", f"NOT MEASURED — {r['thd_error']}"]
    return "\n".join(rows) + "\n"


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    run_thd = "--no-thd" not in sys.argv
    names = args or [p.stem for p in sorted(FROZEN.glob("*.json"))]

    ref_d = load(REF)
    ref = certify("reference", ref_d, run_thd=run_thd, freeze=False)

    results = {}
    for n in names:
        d = load(FROZEN / f"{n}.json")
        r = certify(n, d, run_thd=run_thd)
        results[n] = (d, r)
        cand = HERE / f"cand_{n[-1].lower()}"
        cand.mkdir(exist_ok=True)
        (cand / "scorecard.md").write_text(scorecard(n, d, r, ref))
        print(f"{n}: {M.explain(r['score'])}")

    # figures: everything against the reference, in one frame
    ds = {"reference": ref_d}
    ds.update({n: d for n, (d, _) in results.items()})
    P.bode(ds, "020_bode.png", tag="fig020")
    P.noise(ds, "020_noise.png", tag="fig020n")
    P.bars({n: r["score"].values["irn_uv"] for n, r in
            [("reference", ref)] + [(n, r) for n, (_, r) in results.items()]},
           "020_irn.png", ylabel="IRN 0.5–200 Hz (µVrms)",
           title="S5: input-referred noise", limit=40, limit_label="S5 < 40 µVrms")
    P.bars({n: r["score"].values["p_core_nw"] for n, r in
            [("reference", ref)] + [(n, r) for n, (_, r) in results.items()]},
           "020_power.png", ylabel="filter-core power (nW)",
           title="S6: filter-core power", limit=50, limit_label="S6 < 50 nW")
    print("figures ->", P.FIGS)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
